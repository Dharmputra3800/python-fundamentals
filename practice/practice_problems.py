# Python Practice Problems

# Problem 1: Check whether a number is even or odd
number = 15

if number % 2 == 0:
    print("Even")
else:
    print("Odd")


# Problem 2: Find the largest of two numbers
a = 25
b = 40

if a > b:
    print("Largest:", a)
else:
    print("Largest:", b)


# Problem 3: Calculate the sum of numbers from 1 to 10
total = 0

for i in range(1, 11):
    total += i

print("Sum:", total)
